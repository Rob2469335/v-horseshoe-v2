"""Verify step_agent_stream abort/finally behavior.

Proves:
1. run_id is created
2. GeneratorExit handling occurs
3. aborted outcome is fed
4. trajectory is written in finally
5. trajectory contains correct run_id
6. trajectory records expected aborted status
"""
from __future__ import annotations

import json
from unittest.mock import AsyncMock, MagicMock

import pytest

from runtime_v2.api.agent_service_v2 import AgentServiceV2


@pytest.fixture(autouse=True)
def _isolate(monkeypatch, tmp_path):
    monkeypatch.setattr(
        AgentServiceV2, "_TRAJ_DIR", tmp_path / "trajectories"
    )
    monkeypatch.setattr(
        "runtime_v2.services.checkpointing._CHECKPOINT_DIR", tmp_path / "checkpoints"
    )


def _make_service():
    svc = AgentServiceV2.__new__(AgentServiceV2)
    svc.event_store = MagicMock()
    svc.event_store.append = MagicMock()
    svc.orchestrator = MagicMock()
    svc.orchestrator.events = svc.event_store
    svc.orchestrator.router = MagicMock()
    svc.orchestrator.router.route_model.return_value = ("robs4b", "llama")
    svc.orchestrator.bridge = MagicMock()
    svc.orchestrator.bridge.get_relevant_memories = AsyncMock(return_value="")
    svc.orchestrator.mcp = MagicMock()
    svc.orchestrator.mcp.get_tool_schemas_for_agent.return_value = []
    svc._prompt_repairer = MagicMock()
    svc._prompt_repairer.check_for_past_mistakes = AsyncMock(return_value="")
    svc._agents = {"coder": {"tools": ["filesystem"]}}
    svc._fitness_env_enabled = MagicMock(return_value=False)
    svc._feed_outcome = MagicMock()
    svc._feed_aborted_outcome = MagicMock()
    # _write_run_trajectory: NOT mocked — let the real implementation write files
    svc._record_event = MagicMock()
    svc._record_success = MagicMock()
    svc.get_lesson_manager = MagicMock(return_value=MagicMock(
        render_active_lessons=AsyncMock(return_value=""),
        get_all=AsyncMock(return_value=[]),
    ))
    return svc


class TestAbortTrajectory:
    @pytest.mark.asyncio
    async def test_run_id_created_on_entry(self, tmp_path):
        """The outer wrapper generates a run_id before entering the inner loop."""
        svc = _make_service()

        async def _inner(agent_id, prompt, history=None, delegation_chain=None,
                         research_discharged=False, **kwargs):
            return
            yield  # pragma: no cover

        svc._step_agent_stream_inner = _inner
        async for chunk in svc.step_agent_stream("coder", "test prompt"):
            pass
        # The trajectory file should exist with a valid run_id
        traj_dir = tmp_path / "trajectories"
        assert traj_dir.exists()
        files = list(traj_dir.glob("*.jsonl"))
        assert len(files) == 1
        row = json.loads(files[0].read_text(encoding="utf-8").strip())
        assert row["run_id"]
        assert len(row["run_id"]) == 36  # uuid4 format

    @pytest.mark.asyncio
    async def test_normal_completion_writes_trajectory(self, tmp_path):
        """Normal completion (no abort) still writes the trajectory file."""
        svc = _make_service()

        async def _inner(agent_id, prompt, history=None, delegation_chain=None,
                         research_discharged=False, **kwargs):
            yield {"type": "model_selected", "model": "robs4b"}

        svc._step_agent_stream_inner = _inner
        async for _chunk in svc.step_agent_stream("coder", "test"):
            pass
        traj_dir = tmp_path / "trajectories"
        assert traj_dir.exists()
        files = list(traj_dir.glob("*.jsonl"))
        assert len(files) == 1
        row = json.loads(files[0].read_text(encoding="utf-8").strip())
        assert row["record_type"] == "summary"
        assert row["agent_id"] == "coder"

    @pytest.mark.asyncio
    async def test_trajectory_written_on_abort(self, tmp_path):
        """The trajectory file is created even when the run aborts."""
        svc = _make_service()
        # Let the real _write_run_trajectory execute (not mocked)

        async def _inner(agent_id, prompt, history=None, delegation_chain=None,
                         research_discharged=False, **kwargs):
            yield  # emit nothing, then stop

        svc._step_agent_stream_inner = _inner
        async for _chunk in svc.step_agent_stream("coder", "abort test"):
            pass

        traj_dir = tmp_path / "trajectories"
        assert traj_dir.exists()
        files = list(traj_dir.glob("*.jsonl"))
        assert len(files) == 1

        content = files[0].read_text(encoding="utf-8")
        row = json.loads(content.strip())
        assert row["record_type"] == "summary"
        assert row["agent_id"] == "coder"

    @pytest.mark.asyncio
    async def test_trajectory_run_id_matches(self, tmp_path):
        """The run_id in the trajectory matches the one generated by the outer wrapper."""
        svc = _make_service()

        async def _inner(agent_id, prompt, history=None, delegation_chain=None,
                         research_discharged=False, **kwargs):
            yield  # stop immediately

        svc._step_agent_stream_inner = _inner
        # Let real _write_run_trajectory execute

        async for _chunk in svc.step_agent_stream("coder", "test"):
            pass

        traj_file = list((tmp_path / "trajectories").glob("*.jsonl"))[0]
        row = json.loads(traj_file.read_text(encoding="utf-8").strip())
        assert row["run_id"]
        assert len(row["run_id"]) == 36  # uuid4 format

    @pytest.mark.asyncio
    async def test_trajectory_written_on_exception(self, tmp_path):
        """A RuntimeError in the inner generator triggers trajectory write via finally."""
        svc = _make_service()

        async def _inner(agent_id, prompt, history=None, delegation_chain=None,
                         research_discharged=False, **kwargs):
            yield {"type": "model_selected", "model": "robs4b"}
            raise RuntimeError("test crash")

        svc._step_agent_stream_inner = _inner
        with pytest.raises(RuntimeError):
            async for _chunk in svc.step_agent_stream("coder", "crash test"):
                pass

        traj_dir = tmp_path / "trajectories"
        files = list(traj_dir.glob("*.jsonl"))
        assert len(files) == 1
        row = json.loads(files[0].read_text(encoding="utf-8").strip())
        assert row["status"] == "aborted"
